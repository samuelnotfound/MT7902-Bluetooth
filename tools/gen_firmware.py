"""Turn the MT7902 Bluetooth firmware in firmware/ into a C file the MtkBt kext links in.

  python3 tools/gen_firmware.py <out.c>

The MT7902 blob comes from kernel-firmware/linux-firmware, path
mediatek/BT_RAM_CODE_MT7902_1_1_hdr.bin. See firmware/MT7902-PROVENANCE.json.
The entire SHA-256 is pinned in this script as well as SHA256SUMS. The MediaTek
redistribution license is retained in LICENSES/LICENCE.mediatek.
"""
import hashlib
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from firmware_layout import validate_layout

FW = Path(__file__).resolve().parents[1] / "firmware"
BLOB = ("mtk_bt_fw", "BT_RAM_CODE_MT7902_1_1_hdr.bin")
PIN_PREFIX = "4f53b5e02fbd933172e18caf952bda410a877eaad00561781528cb4aff58dc38"  # pinned here too, so a changed SHA256SUMS cannot slip a new blob in


def pinned():
    out = {}
    for line in (FW / "SHA256SUMS").read_text(encoding="utf-8").splitlines():
        parts = line.split()
        if len(parts) == 2 and len(parts[0]) == 64:
            out[parts[1].lstrip("*")] = parts[0]
    return out


def main(dst):
    sums = pinned()
    sym, name = BLOB
    data = (FW / name).read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if sums.get(name) != digest:
        sys.exit(f"{name}: sha256 {digest} does not match firmware/SHA256SUMS")
    if not digest.startswith(PIN_PREFIX):
        sys.exit(f"{name}: sha256 {digest} does not start with the pinned prefix {PIN_PREFIX}")
    validate_layout(data)
    lines = ["// generated by tools/gen_firmware.py from firmware/, do not edit",
             "#include <stdint.h>",
             f"const unsigned int {sym}_len = {len(data)}u;",
             f'const char {sym}_sha256[] = "{digest}";',
             f'const char {sym}_name[] = "mediatek/{name}";',
             f"const unsigned char {sym}[] __attribute__((aligned(16))) = {{"]
    for i in range(0, len(data), 16):
        lines.append("  " + ", ".join(f"0x{b:02x}" for b in data[i:i + 16]) + ",")
    lines.append("};")
    Path(dst).write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{dst}: {name} {len(data)} bytes sha256 {digest}")


if __name__ == "__main__":
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    main(sys.argv[1])
